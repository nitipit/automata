// Synthetic browser fixture: no provider, user profile, or model interaction.
export async function checkControls(check) {
  const { appTheme, setTheme, clearTheme } = await import('/ui.js');
  const tick = () => new Promise(resolve => setTimeout(resolve, 30));
  const mount = document.createElement('div');
  mount.style.cssText = 'width:min(100%, 320px);';
  document.body.append(mount);
  try {
    const button = document.createElement('ui-button');
    button.textContent = 'Save';
    const field = document.createElement('ui-field');
    field.setAttribute('label', 'Name');
    field.setAttribute('help', 'Enter your name');
    const card = document.createElement('ui-card');
    const heading = document.createElement('h2'); heading.textContent = 'Details';
    card.append(heading, field, button); mount.append(card);
    await tick();
    const nativeButton = button.querySelector('button');
    const input = field.querySelector('input');
    const label = field.querySelector('label');
    check(nativeButton?.type === 'button' && nativeButton.textContent === 'Save', 'controls native button default and name');
    check(label?.control === input && label.textContent === 'Name', 'controls native label association');
    check(input.getAttribute('aria-describedby') === field.querySelector('.field-help').id, 'controls help association');
    let activations = 0; button.addEventListener('click', () => activations++);
    nativeButton.click(); button.disabled = true; nativeButton.click();
    check(activations === 1 && nativeButton.disabled, 'controls disabled native button suppresses activation');
    button.disabled = false; nativeButton.click();
    check(activations === 2, 'controls reenabled action');
    let inputEvents = 0; field.addEventListener('input', () => inputEvents++);
    input.value = 'Ada'; input.dispatchEvent(new Event('input', {bubbles:true}));
    field.setAttribute('error', 'Required');
    check(input.getAttribute('aria-invalid') === 'true' && input.getAttribute('aria-describedby').includes(field.querySelector('.field-error').id), 'controls error association');
    field.removeAttribute('error');
    check(!input.hasAttribute('aria-invalid') && !input.getAttribute('aria-describedby').includes(field.querySelector('.field-error').id), 'controls error removal');
    field.disabled = true; check(input.disabled, 'controls disabled field'); field.disabled = false;
    label.click();
    check(document.activeElement === input, 'controls label focuses input');
    check(input.value === 'Ada' && inputEvents === 1, 'controls input event and value');
    const inputBefore = input, buttonBefore = nativeButton;
    appTheme.set({ roles: { surface: '#234567' } }); await tick();
    check(getComputedStyle(document.querySelector('.chat-panel')).backgroundColor === 'rgb(35, 69, 103)' && getComputedStyle(card).backgroundColor === 'rgb(35, 69, 103)', 'controls and shell share runtime appTheme');
    appTheme.set({}); await tick();
    const originalBackground = getComputedStyle(card).backgroundColor;
    const scope = setTheme(mount, { mode: 'dark' });
    await tick();
    check(field.querySelector('input') === inputBefore && button.querySelector('button') === buttonBefore && document.activeElement === input && input.value === 'Ada', 'controls theme retains DOM focus and value');
    const darkBackground = getComputedStyle(card).backgroundColor;
    check(originalBackground !== darkBackground || appTheme.value.mode === 'dark', 'controls theme changes rendered card');
    nativeButton.click(); check(activations === 3, 'controls theme retains handler');
    const other = document.createElement('ui-card'); other.textContent = 'Other'; document.body.append(other);
    setTheme(other, { mode: 'light', roles: { surface: '#123456' } }); await tick();
    check(getComputedStyle(other).backgroundColor === 'rgb(18, 52, 86)' && getComputedStyle(card).backgroundColor !== 'rgb(18, 52, 86)', 'controls per-instance theme isolation');
    clearTheme(other); other.remove();
    const shadowHost = document.createElement('div'); mount.append(shadowHost);
    const shadow = shadowHost.attachShadow({mode:'open'});
    const shadowCard = document.createElement('ui-card'); shadowCard.textContent = 'Shadow content'; shadow.append(shadowCard);
    await tick();
    check(getComputedStyle(shadowCard).borderTopStyle === 'solid' && getComputedStyle(shadowCard).backgroundColor === getComputedStyle(card).backgroundColor, 'controls structural and inherited style in shadow root');
    const sheet = shadowCard._adapter.cssStyleSheet;
    mount.append(shadowCard); await tick();
    check(!shadow.adoptedStyleSheets.includes(sheet) && document.adoptedStyleSheets.includes(sheet), 'controls reparent sheet lifecycle');
    shadowCard.remove(); await tick();
    check(!document.adoptedStyleSheets.includes(sheet), 'controls disconnect sheet cleanup');
    shadow.append(shadowCard); await tick();
    check(shadow.adoptedStyleSheets.includes(sheet), 'controls reconnect sheet adoption');
    check(card.getBoundingClientRect().width <= mount.getBoundingClientRect().width + 1 && card.scrollWidth <= card.clientWidth + 1, 'controls responsive card width');
    clearTheme(mount); shadowCard.remove();
    void scope;
  } finally { mount.remove(); }
}
