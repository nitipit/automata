export async function checkSessionStatus(check) {
  const title = document.querySelector('#session-name');
  const rename = document.querySelector('#rename');
  const editor = document.querySelector('#rename-form');
  const input = document.querySelector('#session-name-input');
  const error = document.querySelector('#rename-error');
  const transcript = document.querySelector('#messages');
  const frame = value => sock.emit(value);
  const event = value => frame({type:'rpc_event',event:value});
  const snapshot = (messages=[], status='idle', sessionName) => frame({type:'snapshot',messages,state:{status,sessionName}});
  const assistant = (text, extra={}) => ({role:'assistant',content:text ? [{type:'text',text}] : [],...extra});
  const start = () => event({type:'agent_start'});
  const message = value => { event({type:'message_start',message:value}); event({type:'message_end',message:value}); };
  const settled = () => event({type:'agent_settled'});
  check(title.textContent === 'Untitled session', 'unnamed native session fallback');
  snapshot([], 'idle', 'Saved native name');
  check(title.textContent === 'Saved native name', 'snapshot uses native sessionName');
  const row = title.closest('.session-title');
  const geometry = () => JSON.stringify(row.getBoundingClientRect().toJSON());
  const restingGeometry = geometry();
  title.click();
  check(input.value === 'Saved native name' && document.activeElement === input, 'title opens prefilled and focused editor');
  check(input.selectionStart === 0 && input.selectionEnd === input.value.length, 'editor selects displayed name');
  check(geometry() === restingGeometry && rename.getBoundingClientRect().width >= 44, 'editor preserves row and generous pencil hit area');
  input.value = '   '; editor.requestSubmit();
  check(error.textContent.includes('Enter') && !sock.sent.some(x=>x.type==='rename'), 'blank rename rejected without RPC');
  input.value='New name'; editor.requestSubmit();
  let command = sock.sent.at(-1);
  check(command.type==='rename' && command.name==='New name' && title.textContent==='Saved native name', 'rename control is not prompt or optimistic title');
  const renameCount = () => sock.sent.filter(x => x.type === 'rename').length;
  const prompt = document.querySelector('#prompt');
  prompt.focus();
  check(renameCount() === 1, 'blur cannot duplicate pending Enter commit');
  frame({type:'ack',id:command.id,success:false,error:'Write unavailable'});
  check(!editor.hidden && error.textContent.includes('Write unavailable') && input.value==='New name', 'failed rename preserves editor and actionable error');
  check(document.activeElement === prompt, 'failure after blur does not steal focus');
  input.focus(); prompt.focus();
  check(renameCount() === 1, 'unchanged refused value does not retry on blur');
  input.focus(); input.value='Revised name'; prompt.focus(); command=sock.sent.at(-1);
  check(renameCount() === 2 && command.name === 'Revised name', 'changed blur sends one rename');
  frame({type:'ack',id:command.id,success:true,data:{sessionName:'Confirmed name'}});
  check(editor.hidden && title.textContent==='Confirmed name' && document.activeElement===prompt, 'blur shows confirmed native name without moving focus');
  rename.click(); input.value='Enter name'; editor.requestSubmit(); command=sock.sent.at(-1);
  frame({type:'ack',id:command.id,success:true,data:{sessionName:'Enter name'}});
  check(editor.hidden && title.textContent==='Enter name' && document.activeElement===rename, 'focused submission restores pencil focus');
  event({type:'session_info_changed',name:'External rename'});
  check(title.textContent==='External rename', 'native rename event updates title');
  rename.click(); input.value='discard'; input.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  check(editor.hidden && title.textContent==='External rename', 'Escape cancels rename');
  snapshot([], 'idle', 'Reconnect name');
  check(title.textContent==='Reconnect name', 'reconnect snapshot refreshes name');
  start();
  check(transcript.querySelectorAll('.reply-activity').length===1 && transcript.querySelector('.assistant')?.textContent.includes('Responding'), 'first activity has UI-only assistant placeholder');
  message(assistant('Partial answer'));
  check(transcript.querySelectorAll('.assistant').length===1 && transcript.querySelector('.reply-activity')?.closest('article').textContent.includes('Partial answer'), 'activity moves into real latest reply without placeholder duplication');
  event({type:'agent_end'});
  check(!!transcript.querySelector('.reply-activity'), 'activity remains through low-level agent_end');
  settled();
  check(!transcript.querySelector('.reply-activity') && !document.querySelector('#run-status').textContent, 'settlement removes activity without Ready');
  start(); message(assistant('Aborted partial', {stopReason:'aborted'})); settled();
  check([...transcript.querySelectorAll('article')].at(-1).textContent.includes('Aborted partial') && [...transcript.querySelectorAll('article')].at(-1).textContent.includes('interrupted'), 'partial abort retains content and local outcome');
  start(); message(assistant('New successful reply')); settled();
  check(![...transcript.querySelectorAll('article')].at(-1).querySelector('.reply-outcome'), 'old interrupted outcome does not migrate to new reply');
  snapshot([assistant('Historical error',{stopReason:'error',errorMessage:'Provider unavailable'})]);
  check(transcript.querySelector('.reply-outcome')?.textContent.includes('Provider unavailable') && !transcript.querySelector('.reply-activity'), 'history restores native error without transient activity');
  start(); message(assistant('')); settled();
  check(transcript.querySelectorAll('article').length===1, 'empty assistant activity disappears on completion');
  start(); message({role:'assistant',content:[{type:'toolCall',id:'status-tool-only'}]});
  check(!!transcript.querySelector('.reply-activity'), 'tool-only reply carries activity');
  settled(); check(!transcript.querySelector('.reply-activity') && transcript.querySelectorAll('article').length===1, 'tool-only empty reply leaves no fake message');
  start(); message(assistant('Before retry',{stopReason:'error',errorMessage:'Temporary'}));
  event({type:'auto_retry_start',attempt:1});
  message(assistant('Retried successfully')); settled();
  check(![...transcript.querySelectorAll('article')].at(-1).querySelector('.reply-outcome'), 'retry keeps failure beside affected reply only');
  snapshot([], 'running');
  check(!!transcript.querySelector('.reply-activity'), 'running reconnect snapshot shows placeholder');
  frame({type:'host_status',status:'stopping'});
  frame({type:'host_status',status:'idle'});
  check(!transcript.querySelector('.reply-activity') && document.querySelector('#run-status').textContent.includes('interrupted'), 'stop before first reply is input-side status, not persisted message');
  snapshot();
  event({type:'message_start',message:{role:'user',content:[{type:'text',text:'<title>Literal</title>\nภาษาไทย 🐈'}]}});
  check(title.textContent==='<title>Literal</title> ภาษาไทย 🐈' && document.title===title.textContent && !title.querySelector('title'), 'first native user arrival updates literal heading and tab fallback');
  event({type:'session_info_changed',name:'Saved priority'});
  event({type:'message_start',message:{role:'user',content:'Later native user'}});
  check(title.textContent==='Saved priority' && document.title==='Saved priority', 'later user never overwrites explicit saved name');
  snapshot([{role:'assistant',content:'Not a user title'}]);
  check(title.textContent==='Untitled session' && document.title==='Untitled session', 'assistant history is never used for title fallback');
  const plain = { provider: 'fixture', id: 'plain', name: 'Plain' };
  const reasoning = { provider: 'fixture', id: 'r', name: 'Reasoning' };
  const model = document.querySelector('select[name=model]');
  const thinking = document.querySelector('select[name=thinking-level]');
  const controls = document.querySelector('#runtime-controls-status');
  const composer = document.querySelector('#composer');
  const send = document.querySelector('#send');
  const plainKey = JSON.stringify(['fixture', 'plain']);
  const reasoningKey = JSON.stringify(['fixture', 'r']);
  const settings = (model, thinkingLevel, thinkingLevels) => ({status:'idle', model, modelChoices:[plain, reasoning], thinkingLevel, thinkingLevels});
  const change = (input, value) => { input.value = value; input.dispatchEvent(new Event('change', { bubbles:true })); };
  frame({type:'snapshot',messages:[],state:{...settings(plain, 'off', ['off']),modelChoices:[]}});
  check(model.disabled && [...model.options].every(option => option.disabled) && controls.textContent.includes('No pinned models'), 'empty pins never fall back to available model');
  frame({type:'host_status',...settings(plain, 'off', ['off']),controlsError:'Native controls unavailable'});
  check(model.disabled && thinking.disabled && controls.textContent.includes('unavailable'), 'discovery failure distinct from empty pins');
  frame({type:'host_status',...settings(plain, 'off', ['off'])});
  check(model.value === plainKey && thinking.value === 'off' && !model.disabled, 'authoritative settings initialize native controls');
  check(model.closest('ui-select') && thinking.closest('ui-select') && model.labels[0]?.textContent === 'Model' && thinking.labels[0]?.textContent === 'Thinking' && thinking.getBoundingClientRect().right < send.getBoundingClientRect().left, 'native shared selects stay labeled and left of Send');
  prompt.value = 'Keep draft';
  change(model, reasoningKey);
  command = sock.sent.at(-1);
  check(command.type === 'set_model' && command.provider === 'fixture' && command.modelId === 'r' && command.sessionId === 'browser-fixture', 'model change sends scoped native request');
  check(model.value === plainKey && model.disabled && thinking.disabled && send.disabled, 'wait for confirmation and prevent prompt racing change');
  composer.requestSubmit();
  check(sock.sent.at(-1) === command && prompt.value === 'Keep draft', 'race guard keeps typed prompt intact');
  frame({type:'ack',id:command.id,success:false,error:'Not permitted'});
  check(model.value === plainKey && thinking.value === 'off' && !model.disabled && controls.textContent.includes('Not permitted') && prompt.value === 'Keep draft', 'model refusal preserves confirmed settings and draft and is visible');
  change(model, reasoningKey); command = sock.sent.at(-1);
  frame({type:'host_status',...settings(reasoning, 'low', ['off', 'low', 'high'])});
  frame({type:'ack',id:command.id,success:true});
  check(model.value === reasoningKey && thinking.value === 'low' && thinking.options.length === 3 && !controls.textContent, 'native model change atomically renders effective thinking and allowed levels');
  change(thinking, 'high'); command = sock.sent.at(-1);
  check(command.type === 'set_thinking_level' && command.level === 'high' && thinking.value === 'low', 'thinking command constrained to authoritative levels without optimism');
  frame({type:'ack',id:command.id,success:false,error:'Not permitted'});
  check(thinking.value === 'low' && model.value === reasoningKey && !thinking.disabled && controls.textContent.includes('Not permitted') && prompt.value === 'Keep draft', 'thinking refusal preserves confirmed settings and draft and is visible');
  change(thinking, 'high'); command = sock.sent.at(-1);
  frame({type:'host_status',...settings(reasoning, 'high', ['off', 'low', 'high'])});
  frame({type:'ack',id:command.id,success:true});
  check(thinking.value === 'high' && prompt.value === 'Keep draft', 'thinking confirmation applies without changing draft');
  frame({type:'host_status',...settings(reasoning, 'high', ['off', 'low', 'high']),status:'running'});
  check(model.disabled && thinking.disabled && !send.disabled && send.dataset.action === 'stop', 'active reply locks both settings but allows Stop');
  prompt.value='';
  snapshot(); document.querySelector('#run-status').textContent=''; sock.sent.length=0;
}
